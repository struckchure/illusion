// Command gen generates the arity variants of queries and system adapters.
//
// Run it with `go generate` from the repository root.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strings"
	"text/template"
)

const maxQuery = 8
const maxParams = 8

var letters = []string{"A", "B", "C", "D", "E", "F", "G", "H"}

type arity struct {
	N     int
	Types []string
}

// TypeParams is "A, B any" (or "" for arity 0).
func (a arity) TypeParams() string {
	if a.N == 0 {
		return ""
	}
	return strings.Join(a.Types, ", ") + " any"
}

// Count is "no parameters", "1 parameter", "2 parameters", ...
func (a arity) Count() string {
	switch a.N {
	case 0:
		return "no parameters"
	case 1:
		return "1 parameter"
	}
	return fmt.Sprintf("%d parameters", a.N)
}

// TypeArgs is "A, B".
func (a arity) TypeArgs() string { return strings.Join(a.Types, ", ") }

// Ptrs is "*A, *B".
func (a arity) Ptrs() string { return join(a.Types, "*%[1]s", ", ") }

// Vars is "a, b".
func (a arity) Vars() string { return strings.ToLower(a.TypeArgs()) }

// Nils is "nil, nil".
func (a arity) Nils() string { return strings.Repeat("nil, ", a.N-1) + "nil" }

// Decls is "a *A, b *B".
func (a arity) Decls() string {
	parts := make([]string, a.N)
	for i, t := range a.Types {
		parts[i] = strings.ToLower(t) + " *" + t
	}
	return strings.Join(parts, ", ")
}

// ParamTypeParams is "A, B any, PA paramPtr[A], PB paramPtr[B]".
func (a arity) ParamTypeParams() string {
	if a.N == 0 {
		return ""
	}
	return a.TypeParams() + ", " + join(a.Types, "P%[1]s paramPtr[%[1]s]", ", ")
}

// ParamTypeArgs is "A, B, PA, PB".
func (a arity) ParamTypeArgs() string {
	if a.N == 0 {
		return ""
	}
	return a.TypeArgs() + ", " + join(a.Types, "P%[1]s", ", ")
}

// PTypes is "PA, PB".
func (a arity) PTypes() string { return join(a.Types, "P%[1]s", ", ") }

// Fields is "a A; b B" as struct fields.
func (a arity) Fields() string {
	parts := make([]string, a.N)
	for i, t := range a.Types {
		parts[i] = "p" + strings.ToLower(t) + " " + t
	}
	return strings.Join(parts, "\n")
}

// Inits calls InitParam on each field.
func (a arity) Inits() string {
	return join(a.Types, "P%[1]s(&s.p"+"%[2]s).InitParam(w)", "\n")
}

// Args is "&s.pa, &s.pb".
func (a arity) Args() string { return join(a.Types, "&s.p%[2]s", ", ") }

func join(types []string, pattern, sep string) string {
	parts := make([]string, len(types))
	for i, t := range types {
		parts[i] = fmt.Sprintf(pattern, t, strings.ToLower(t))
	}
	return strings.Join(parts, sep)
}

func arities(from, to int) []arity {
	out := []arity{}
	for n := from; n <= to; n++ {
		out = append(out, arity{N: n, Types: letters[:n]})
	}
	return out
}

func main() {
	render("query_gen.go", queryTmpl, arities(1, maxQuery))
	render("system_gen.go", systemTmpl, arities(0, maxParams))
}

func render(file, src string, data any) {
	tmpl := template.Must(template.New(file).Parse(src))
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		panic(err)
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		os.WriteFile(file, buf.Bytes(), 0o644)
		panic(fmt.Errorf("%s: %w", file, err))
	}
	if err := os.WriteFile(file, out, 0o644); err != nil {
		panic(err)
	}
}

